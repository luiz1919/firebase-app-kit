import assert from 'node:assert/strict'
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { after, test } from 'node:test'
import { firebaseAppKit, readFirebaseConfigFile, serviceWorkerSource } from '../src/vite.ts'

const dir = mkdtempSync(join(tmpdir(), 'firebase-app-kit-'))
after(() => rmSync(dir, { recursive: true, force: true }))

// This is how the Firebase console copies it.
const CONSOLE_SNIPPET = `// Import the functions you need from the SDKs you need
import { initializeApp } from "firebase/app";
// Your web app's Firebase configuration
const firebaseConfig = {
  apiKey: "key",
  authDomain: "demo.firebaseapp.com",
  "projectId": "demo",
  storageBucket: "demo.firebasestorage.app",
  messagingSenderId: "123",
  appId: "1:123:web:abc",
  other: "ignored"
};
const app = initializeApp(firebaseConfig);
`

test('reads the firebaseConfig object without running the file', async () => {
  const file = join(dir, 'firebaseConfig')
  writeFileSync(file, CONSOLE_SNIPPET)
  assert.deepEqual(await readFirebaseConfigFile(file), {
    apiKey: 'key',
    authDomain: 'demo.firebaseapp.com',
    projectId: 'demo',
    storageBucket: 'demo.firebasestorage.app',
    messagingSenderId: '123',
    appId: '1:123:web:abc',
  })
})

test('returns {} without a file', async () => {
  assert.deepEqual(await readFirebaseConfigFile(join(dir, 'missing')), {})
})

test('an incomplete file is an error', async () => {
  const file = join(dir, 'incomplete')
  writeFileSync(file, 'const firebaseConfig = { apiKey: "key" }')
  await assert.rejects(readFirebaseConfigFile(file), /apiKey, projectId and appId/)
})

type ConfigHook = (config: { root?: string }, env: { command: 'build' | 'serve'; mode: string }) => Promise<{ define: Record<string, string> }>

test('the plugin defines version, commit, date and config', async () => {
  writeFileSync(join(dir, 'package.json'), JSON.stringify({ version: '1.2.3' }))
  const plugin = firebaseAppKit({ firebaseConfigFile: 'firebaseConfig' })
  const config = plugin.config as unknown as ConfigHook

  const build = await config({ root: dir }, { command: 'build', mode: 'production' })
  assert.equal(JSON.parse(build.define.__APP_VERSION__), '1.2.3')
  assert.equal(typeof JSON.parse(build.define.__APP_COMMIT__), 'string')
  assert.ok(!Number.isNaN(Date.parse(JSON.parse(build.define.__BUILD_TIME__))))
  assert.equal(JSON.parse(build.define.__FIREBASE_CONFIG__).projectId, 'demo')

  const dev = await config({ root: dir }, { command: 'serve', mode: 'development' })
  assert.equal(JSON.parse(dev.define.__BUILD_TIME__), '')
})

test('without firebaseConfigFile the config is {}', async () => {
  const config = firebaseAppKit().config as unknown as ConfigHook
  const result = await config({ root: dir }, { command: 'build', mode: 'production' })
  assert.deepEqual(JSON.parse(result.define.__FIREBASE_CONFIG__), {})
})

type PluginHooks = {
  configResolved: (config: { publicDir: string }) => void
  generateBundle: (this: { emitFile: (file: { type: string; fileName: string; source: string }) => void }) => void
}
const swOptions = { cacheName: 'test-app-v1', staticFiles: ['/manifest.webmanifest', '/icons/icon-192.png'] }

test('serviceWorkerSource fills the shared template with the app values', () => {
  const source = serviceWorkerSource(swOptions)
  assert.match(source, /^\/\/ Generated by firebase-app-kit/)
  assert.match(source, /const CACHE = "test-app-v1"/)
  assert.match(source, /const STATIC_FILES = \["\/manifest\.webmanifest","\/icons\/icon-192\.png"\]/)
  assert.match(source, /async function storeShell/)
  assert.doesNotThrow(() => new Function(source))
  assert.throws(() => serviceWorkerSource({ ...swOptions, cacheName: 'bad name' }), /cacheName/)
  assert.throws(() => serviceWorkerSource({ ...swOptions, staticFiles: ['icon.png'] }), /staticFiles/)
})

test('with serviceWorker the plugin emits sw.js, and refuses a public/sw.js', () => {
  const publicDir = mkdtempSync(join(tmpdir(), 'firebase-app-kit-public-'))
  try {
    const hooks = firebaseAppKit({ serviceWorker: swOptions }) as unknown as PluginHooks
    hooks.configResolved({ publicDir })
    const emitted: { fileName: string; source: string }[] = []
    hooks.generateBundle.call({ emitFile: (file) => emitted.push(file) })
    assert.deepEqual(emitted.map((file) => file.fileName), ['sw.js'])
    assert.equal(emitted[0].source, serviceWorkerSource(swOptions))
    writeFileSync(join(publicDir, 'sw.js'), '// old')
    assert.throws(() => hooks.configResolved({ publicDir }), /public\/sw\.js exists/)
  } finally {
    rmSync(publicDir, { recursive: true, force: true })
  }
})

test('without serviceWorker the plugin emits nothing', () => {
  const hooks = firebaseAppKit() as unknown as PluginHooks
  const emitted: unknown[] = []
  hooks.generateBundle.call({ emitFile: (file) => emitted.push(file) })
  assert.equal(emitted.length, 0)
})
